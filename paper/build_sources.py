"""Build the manuscript appendix from the actual current source files."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
paths = [root / 'run_all.py'] + sorted((root / 'src').rglob('*.py'))
exclude = {'make_accuracy_report.py',
           'validate_numerics.py', 'validate_q4_accuracy.py',
           'verify_accuracy_reproduction.py'}
paths += [p for p in sorted((root / 'scripts').glob('*.py')) if p.name not in exclude]
paths += sorted((root / 'tests').glob('*.py'))
paths += [Path(__file__).resolve()]
lines = ['% Generated by paper/build_sources.py; source is included directly.']
for p in paths:
    if not p.is_file() or not p.read_text(encoding='utf-8-sig').strip():
        continue
    rel = p.relative_to(root).as_posix()
    safe = rel.replace('_', r'\_')
    lines += [r'\subsubsection*{\texttt{' + safe + '}}',
              r'\lstinputlisting[language=Python]{../' + rel + '}']
(root / 'paper' / 'source_listings.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Included {sum(x.startswith(chr(92)+"lstinputlisting") for x in lines)} source files')
